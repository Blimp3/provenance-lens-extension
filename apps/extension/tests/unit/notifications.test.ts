import type {
  NormalizedProvenanceResult,
  ResultToastBinding,
} from "@provenance-lens/shared";
import { describe, expect, it } from "vitest";

import {
  detectedToastCopy,
  errorToastCopy,
  matchesResultToastBinding,
  matchesToastActionBinding,
  noSignalToastCopy,
  progressToastMessage,
  removePageResultToastBindings,
  removeResultToastBinding,
  replaceResultToastBinding,
  resultDetailsUrl,
  spendToastAction,
  toastActions,
  upsertResultToastBinding,
} from "../../src/notifications.js";

const baseResult: NormalizedProvenanceResult = {
  verdict: "openai_signal_detected",
  summary: "Detected signals: C2PA and SynthID.",
  signals: [
    {
      type: "c2pa",
      outcome: "detected",
      validationState: "trusted",
      issuer: null,
      model: null,
      generatedAt: null,
    },
    {
      type: "synthid",
      outcome: "detected",
      validationState: null,
      issuer: null,
      model: null,
      generatedAt: null,
    },
  ],
  warnings: [],
  checkedAt: "2026-09-01T10:00:00.000Z",
  requestId: "123e4567-e89b-42d3-a456-426614174000",
};

describe("toast copies and result links", () => {
  it("describes detected signals without exposing arbitrary page data", () => {
    expect(detectedToastCopy(baseResult)).toEqual({
      title: "OpenAI provenance detected",
      message: "Detected signals: C2PA and SynthID.",
    });
  });

  it("keeps the no-signal limitation explicit", () => {
    expect(noSignalToastCopy()).toEqual({
      title: "No supported OpenAI signal detected",
      message:
        "This does not prove that the image is human-made or that it was not generated by another AI system.",
    });
  });

  it("keeps errors and result details on the extension origin", () => {
    expect(errorToastCopy("Backend unavailable").message).toBe(
      "Backend unavailable",
    );
    expect(
      resultDetailsUrl("chrome-extension://test-id/details.html", "123"),
    ).toBe("chrome-extension://test-id/details.html?id=123");
  });

  it("opens details only for the exact bound result document", () => {
    const binding: ResultToastBinding = {
      resultId: "123e4567-e89b-42d3-a456-426614174000",
      sessionToken: "223e4567-e89b-42d3-a456-426614174000",
      tabId: 7,
      frameId: 3,
      documentId: "document-1",
      actions: ["details"],
    };
    const request = {
      resultId: binding.resultId,
      sessionToken: binding.sessionToken,
    };
    const sender = {
      tabId: binding.tabId,
      frameId: binding.frameId,
      documentId: binding.documentId,
    };
    expect(matchesResultToastBinding(binding, request, sender)).toBe(true);
    expect(
      matchesResultToastBinding(binding, request, {
        ...sender,
        documentId: "navigated-document",
      }),
    ).toBe(false);
    expect(
      matchesResultToastBinding(binding, request, {
        ...sender,
        frameId: 0,
      }),
    ).toBe(false);
    expect(
      matchesResultToastBinding(binding, request, {
        ...sender,
        tabId: undefined,
      }),
    ).toBe(false);
    expect(
      matchesResultToastBinding(
        binding,
        { ...request, resultId: "323e4567-e89b-42d3-a456-426614174000" },
        sender,
      ),
    ).toBe(false);
    expect(
      matchesResultToastBinding(
        binding,
        {
          ...request,
          sessionToken: "423e4567-e89b-42d3-a456-426614174000",
        },
        sender,
      ),
    ).toBe(false);
  });

  it("keeps a bounded single result binding per document", () => {
    const first: ResultToastBinding = {
      resultId: "123e4567-e89b-42d3-a456-426614174000",
      sessionToken: "223e4567-e89b-42d3-a456-426614174000",
      tabId: 7,
      frameId: 3,
      documentId: "document-1",
      actions: ["details"],
    };
    const replacement = {
      ...first,
      resultId: "323e4567-e89b-42d3-a456-426614174000",
      sessionToken: "423e4567-e89b-42d3-a456-426614174000",
    };
    const otherDocument = {
      ...first,
      resultId: "523e4567-e89b-42d3-a456-426614174000",
      sessionToken: "623e4567-e89b-42d3-a456-426614174000",
      documentId: "document-2",
    };
    const bindings = upsertResultToastBinding(
      upsertResultToastBinding([first], otherDocument, 2),
      replacement,
      2,
    );
    expect(bindings).toEqual([otherDocument, replacement]);
    expect(removeResultToastBinding(bindings, replacement)).toEqual([
      otherDocument,
    ]);
    expect(
      removePageResultToastBindings(bindings, {
        tabId: otherDocument.tabId,
        frameId: otherDocument.frameId,
        documentId: otherDocument.documentId,
      }),
    ).toEqual([replacement]);
  });

  it("puts Details first on a saved result and keeps at most two buttons", () => {
    const resultId = "123e4567-e89b-42d3-a456-426614174000";
    expect(toastActions(resultId)).toEqual(["details"]);
    expect(toastActions(resultId, ["check-synthid"])).toEqual([
      "details",
      "check-synthid",
    ]);
    expect(toastActions(resultId, ["grant-access", "details"])).toEqual([
      "details",
      "grant-access",
    ]);
    expect(toastActions(null, ["details", "history"])).toEqual(["history"]);
    expect(toastActions(null, ["history", "check-synthid", "retry"])).toEqual([
      "history",
      "check-synthid",
    ]);
    expect(progressToastMessage("page.example", "DigiBot check")).toBe(
      "page.example · DigiBot check",
    );
    expect(progressToastMessage("", "Video")).toBe("This page · Video");
  });

  it("accepts a toast button only from its bound document, once for Retry, Cancel and Details", () => {
    const binding: ResultToastBinding = {
      resultId: null,
      sessionToken: "223e4567-e89b-42d3-a456-426614174000",
      tabId: 7,
      frameId: 0,
      documentId: "document-1",
      actions: ["retry", "history"],
      retry: {
        actionId: "send-page-link",
        url: "https://page.example/watch",
        options: { output: "mp3" },
      },
    };
    const sender = { tabId: 7, frameId: 0, documentId: "document-1" };
    const request = {
      sessionToken: binding.sessionToken,
      action: "retry",
    } as const;
    expect(matchesToastActionBinding(binding, request, sender)).toBe(true);
    expect(
      matchesToastActionBinding(
        binding,
        { ...request, action: "connect-digibot" },
        sender,
      ),
    ).toBe(false);
    expect(
      matchesToastActionBinding(binding, request, {
        ...sender,
        documentId: "navigated-document",
      }),
    ).toBe(false);
    expect(
      matchesToastActionBinding(binding, request, { ...sender, frameId: 2 }),
    ).toBe(false);

    const afterRetry = spendToastAction(binding, "retry");
    expect(afterRetry).toEqual({
      resultId: null,
      sessionToken: binding.sessionToken,
      tabId: 7,
      frameId: 0,
      documentId: "document-1",
      actions: ["history"],
    });
    // History opens a page and may be used again.
    expect(spendToastAction(afterRetry as ResultToastBinding, "history")).toBe(
      afterRetry,
    );
    expect(
      spendToastAction({ ...binding, actions: ["cancel"] }, "cancel"),
    ).toBeNull();
    expect(
      spendToastAction(
        { ...binding, actions: ["stop-waiting"] },
        "stop-waiting",
      ),
    ).toBeNull();

    const result: ResultToastBinding = {
      ...binding,
      resultId: "123e4567-e89b-42d3-a456-426614174000",
      actions: ["details", "check-synthid"],
    };
    const afterDetails = spendToastAction(result, "details");
    expect(afterDetails).toMatchObject({
      resultId: null,
      actions: ["check-synthid"],
    });
    expect(replaceResultToastBinding([result], result, afterDetails)).toEqual([
      afterDetails,
    ]);
    expect(replaceResultToastBinding([result], result, null)).toEqual([]);
  });
});
